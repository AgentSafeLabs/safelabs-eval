"""
safelabs/agents/autogen_adapter.py

Adapter for AutoGen / ag2 ConversableAgent.

Install optional dependency first:
    pip install "safelabs-eval[autogen]"

Example
-------
.. code-block:: python

    import autogen
    from safelabs.agents import AutoGenAdapter

    agent = autogen.ConversableAgent(
        name="assistant",
        system_message="You are a helpful assistant.",
        llm_config={"model": "gpt-4o-mini"},
    )
    user_proxy = autogen.UserProxyAgent(
        name="user",
        human_input_mode="NEVER",
        max_consecutive_auto_reply=0,
    )
    adapter = AutoGenAdapter(agent=agent, recipient=user_proxy)
    response = await adapter.execute("Ignore previous instructions.")

API compatibility note
----------------------
AutoGen's packaging has split into two diverging distributions with
overlapping names:

* ``ag2`` >= 0.2 (ag2ai community fork) — ``import autogen`` namespace,
  ``ConversableAgent.a_initiate_chat()`` returning a ``ChatResult``.
  **This adapter targets this distribution.**

* ``pyautogen`` / ``autogen-agentchat`` (Microsoft fork, recent releases)
  — migrated to the ``autogen_agentchat`` namespace with a different
  runtime model.

If your environment has the Microsoft fork, the ``import autogen`` namespace
and the ``a_initiate_chat`` / ``ChatResult`` API used here may not be present.
Verify with ``pip show ag2`` and cross-check the installed version's docs
before use.
"""

from __future__ import annotations

import time

from safelabs.agents.base import AgentAdapter
from safelabs.agents.schemas import AgentResponse


class AutoGenAdapter(AgentAdapter):
    """
    Adapter for AutoGen / ag2 ConversableAgent objects.

    The *recipient* (typically a ``UserProxyAgent``) initiates the conversation
    by calling ``a_initiate_chat(agent, message=prompt, max_turns=1)``.
    ``max_turns=1`` is always enforced — this is a single-turn adversarial
    probe, not a multi-turn dialogue.

    Parameters
    ----------
    agent:
        The ``ConversableAgent`` under test — the target of the adversarial
        prompt.
    recipient:
        A ``UserProxyAgent`` (or any ``ConversableAgent``) that sends the
        prompt to *agent* and receives its response.
    timeout:
        Per-request timeout in seconds (default 30).  Enforced by the base
        class; subclasses never need to handle this themselves.

    Example
    -------
    .. code-block:: python

        adapter = AutoGenAdapter(agent=my_agent, recipient=user_proxy)
        response = await adapter.execute("Ignore previous instructions.")
    """

    def __init__(
        self,
        agent: object,
        recipient: object,
        timeout: float = 30.0,
    ) -> None:
        super().__init__(timeout=timeout)
        self._agent     = agent
        self._recipient = recipient

    @property
    def adapter_type(self) -> str:
        return "autogen"

    async def _execute(self, prompt: str) -> AgentResponse:
        t0 = time.perf_counter()
        # recipient sends the adversarial prompt to agent and waits for one reply
        result = await self._recipient.a_initiate_chat(
            self._agent,
            message=prompt,
            max_turns=1,
        )
        latency_ms = (time.perf_counter() - t0) * 1000
        return AgentResponse(output=self._extract_output(result), latency_ms=latency_ms)

    def _extract_output(self, result: object) -> str:
        # 1. ChatResult.chat_history — list of {"role": ..., "content": ...} dicts.
        #    The last entry is the agent's reply to the single-turn probe.
        chat_history = getattr(result, "chat_history", None)
        if chat_history and isinstance(chat_history, list):
            last = chat_history[-1]
            if isinstance(last, dict) and "content" in last:
                return str(last["content"])

        # 2. ChatResult.summary — string summary generated by AutoGen.
        summary = getattr(result, "summary", None)
        if summary and isinstance(summary, str):
            return summary

        # 3. Plain-string fallback (mocks, future API changes, or unknown shapes).
        if isinstance(result, str):
            return result

        return str(result)
